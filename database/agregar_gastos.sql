-- Ejecutar en la base local y en Neon. No elimina datos existentes.
BEGIN;
CREATE TABLE IF NOT EXISTS gastos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  concepto varchar(100) NOT NULL,
  categoria varchar(40) NOT NULL,
  fecha_pago date NOT NULL,
  monto numeric(12,2) NOT NULL CHECK (monto > 0),
  UNIQUE (concepto, fecha_pago)
);

-- Ocho meses, alineados con los pagos ficticios existentes (enero-agosto 2026).
-- Gastos efectivamente pagados; los montos son ilustrativos, no presupuestos.
INSERT INTO gastos (concepto, categoria, fecha_pago, monto)
SELECT concepto, categoria, (DATE '2026-01-10' + mes * INTERVAL '1 month')::date,
       round(base * (1 + mes * 0.04), 2)
FROM (VALUES
  ('Electricidad', 'Servicios', 180000::numeric),
  ('Gas', 'Servicios', 95000::numeric),
  ('Agua', 'Servicios', 65000::numeric),
  ('Internet', 'Servicios', 40000::numeric),
  ('Limpieza', 'Gastos fijos', 220000::numeric),
  ('Seguro del club', 'Gastos fijos', 110000::numeric),
  ('Mantenimiento de instalaciones', 'Gastos fijos', 180000::numeric),
  ('Honorarios de profesores', 'Gastos fijos', 450000::numeric)
) AS conceptos(concepto, categoria, base)
CROSS JOIN generate_series(0, 7) AS meses(mes)
ON CONFLICT (concepto, fecha_pago) DO NOTHING;
COMMIT;
