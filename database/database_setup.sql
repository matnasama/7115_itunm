CREATE TABLE socios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(80) NOT NULL,
  apellido varchar(80) NOT NULL,
  dni varchar(20) NOT NULL UNIQUE,
  fecha_nacimiento date NOT NULL,
  telefono varchar(30),
  activo boolean NOT NULL DEFAULT true
);
CREATE TABLE categorias (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(80) NOT NULL UNIQUE,
  descripcion text
);
CREATE TABLE profesores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(80) NOT NULL,
  apellido varchar(80) NOT NULL,
  telefono varchar(30)
);
CREATE TABLE actividades (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL UNIQUE,
  descripcion text,
  profesor_id integer NOT NULL REFERENCES profesores(id),
  categoria_id integer NOT NULL REFERENCES categorias(id)
);
CREATE TABLE inscripciones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  socio_id integer NOT NULL REFERENCES socios(id),
  actividad_id integer NOT NULL REFERENCES actividades(id),
  fecha_inscripcion date NOT NULL,
  activa boolean NOT NULL DEFAULT true,
  UNIQUE (socio_id, actividad_id)
);
CREATE TABLE cuotas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  socio_id integer NOT NULL REFERENCES socios(id),
  periodo date NOT NULL CHECK (EXTRACT(DAY FROM periodo) = 1),
  monto numeric(12,2) NOT NULL CHECK (monto > 0),
  estado varchar(10) NOT NULL CHECK (estado IN ('pagada', 'pendiente')),
  UNIQUE (socio_id, periodo)
);
CREATE TABLE pagos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cuota_id integer NOT NULL REFERENCES cuotas(id),
  fecha_pago date NOT NULL,
  monto numeric(12,2) NOT NULL CHECK (monto > 0),
  medio_pago varchar(20) NOT NULL CHECK (medio_pago IN ('efectivo', 'transferencia', 'tarjeta'))
);
CREATE INDEX ON inscripciones (actividad_id);
CREATE INDEX ON cuotas (periodo);
CREATE INDEX ON pagos (fecha_pago);

